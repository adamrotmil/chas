def to_jsonl(rows: Iterable[Dict[str, Any]]) -> str:
    return "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows)


def validate_model_starter(
    sft_examples: Sequence[ModelStarterSFTExample],
    dpo_pairs: Sequence[ModelStarterDPOPair],
) -> Dict[str, Any]:
    issues: List[ValidationIssue] = []
    seen_sft: set[str] = set()
    seen_dpo: set[str] = set()
    for example in sft_examples:
        example_id = example.example_id
        if not _non_empty_string(example_id):
            issues.append(ValidationIssue("sft", example_id, "id", "error", "id_missing", "SFT id is required."))
        elif example_id in seen_sft:
            issues.append(ValidationIssue("sft", example_id, "id", "error", "duplicate_id", "SFT ids must be unique."))
        seen_sft.add(example_id)
        if not _non_empty_string(example.instruction):
            issues.append(ValidationIssue("sft", example_id, "instruction", "error", "instruction_empty", "Instruction is required."))
        if not _non_empty_string(example.response):
            issues.append(ValidationIssue("sft", example_id, "response", "error", "response_empty", "Response is required."))
        elif len(example.response.strip()) < 40:
            issues.append(ValidationIssue("sft", example_id, "response", "warning", "response_unusually_short", "Response is unusually short for voice training."))
        text = "\n".join([example.instruction or "", example.response or "", example.provenance or "", example.notes or ""])
        if (EMAIL_RE.search(text) or NAME_RE.search(text)) and not example.pii_tags:
            issues.append(ValidationIssue("sft", example_id, "pii_tags", "warning", "pii_tags_empty", "Possible names/emails appear but pii_tags is empty."))

    for pair in dpo_pairs:
        example_id = pair.example_id
        if not _non_empty_string(example_id):
            issues.append(ValidationIssue("dpo", example_id, "id", "error", "id_missing", "DPO id is required."))
        elif example_id in seen_dpo:
            issues.append(ValidationIssue("dpo", example_id, "id", "error", "duplicate_id", "DPO ids must be unique."))
        seen_dpo.add(example_id)
        for field, value in [("prompt", pair.prompt), ("chosen", pair.chosen), ("rejected", pair.rejected)]:
            if not _non_empty_string(value):
                issues.append(ValidationIssue("dpo", example_id, field, "error", f"{field}_empty", f"DPO {field} is required."))
        if _non_empty_string(pair.chosen) and pair.chosen.strip() == pair.rejected.strip():
            issues.append(ValidationIssue("dpo", example_id, "rejected", "error", "chosen_rejected_identical", "Chosen and rejected must be different."))
        if _non_empty_string(pair.chosen) and len(pair.chosen.strip()) < 40:
            issues.append(ValidationIssue("dpo", example_id, "chosen", "warning", "chosen_unusually_short", "Chosen response is unusually short."))

    error_count = len([issue for issue in issues if issue.severity == "error"])
    warning_count = len([issue for issue in issues if issue.severity == "warning"])
    return {
        "checked_sft_count": len(sft_examples),
        "checked_dpo_count": len(dpo_pairs),
        "error_count": error_count,
        "warning_count": warning_count,
        "ready": error_count == 0,
        "issues": [issue.as_dict() for issue in issues],
    }


def split_sft_ids(rows: Sequence[Dict[str, Any]], val_ratio: float = 0.05, seed: int = 42) -> Dict[str, Any]:
    bounded_ratio = min(max(val_ratio, 0.0), 0.5)
    indexed = list(enumerate(rows))
    random.Random(seed).shuffle(indexed)
    if len(indexed) <= 1:
        val_count = 0
    else:
        val_count = max(1, min(len(indexed) - 1, math.floor(len(indexed) * bounded_ratio + 0.5)))
    val_indexes = {index for index, _row in indexed[:val_count]}
    train_rows = [row for index, row in enumerate(rows) if index not in val_indexes]
    val_rows = [row for index, row in enumerate(rows) if index in val_indexes]
    return {
        "source_count": len(rows),
        "train_count": len(train_rows),
        "val_count": len(val_rows),
        "train_ids": [str(row["id"]) for row in train_rows],
        "val_ids": [str(row["id"]) for row in val_rows],
        "deterministic_seed": seed,
        "val_ratio": bounded_ratio,
        "train_rows": train_rows,
        "val_rows": val_rows,
    }


def package_file_contents(
    session: Session,
    *,
    include_split: bool = False,
    val_ratio: float = 0.05,
    seed: int = 42,
    seed_if_empty: bool = True,
) -> List[tuple[str, str]]:
    if seed_if_empty:
        ensure_seed_data(session)
    sft_rows = [sft_row(example) for example in _active_sft(session)]
    dpo_rows = [dpo_row(pair) for pair in _active_dpo(session)]
    split = split_sft_ids(sft_rows, val_ratio=val_ratio, seed=seed)

    files = [
        (f"{PACKAGE_ROOT}/data/charles_sft.jsonl", to_jsonl(sft_rows)),
        (f"{PACKAGE_ROOT}/data/charles_dpo.jsonl", to_jsonl(dpo_rows)),
    ]
    if include_split:
        files.extend(
            [
                (f"{PACKAGE_ROOT}/data/charles_sft.train.jsonl", to_jsonl(split["train_rows"])),
                (f"{PACKAGE_ROOT}/data/charles_sft.val.jsonl", to_jsonl(split["val_rows"])),
            ]
        )
    files.extend(
        [
            (f"{PACKAGE_ROOT}/data/README.md", DATA_README),
            (f"{PACKAGE_ROOT}/configs/train_sft.yaml", TRAIN_CONFIG),
            (f"{PACKAGE_ROOT}/scripts/check_jsonl.py", CHECK_JSONL_SCRIPT + "\n"),
            (f"{PACKAGE_ROOT}/scripts/split_canary_val.py", SPLIT_SCRIPT + "\n"),
            (f"{PACKAGE_ROOT}/.gitignore", PACKAGE_GITIGNORE),
        ]
    )
    return files


def package_preview(session: Session, *, seed_if_empty: bool = True) -> Dict[str, Any]:
    files = package_file_contents(session, seed_if_empty=seed_if_empty)
    file_summaries = []
    content_digest = hashlib.sha256()
    by_path = dict(files)
    for path, text in files:
        encoded = text.encode("utf-8")
        content_digest.update(path.encode("utf-8"))
        content_digest.update(b"\0")
        content_digest.update(encoded)
        file_summaries.append(
            {
                "path": path,
                "byte_count": len(encoded),
                "sha256": hashlib.sha256(encoded).hexdigest(),
            }
        )
    validation = validate_model_starter(_active_sft(session), _active_dpo(session))
    return {
        "package_tree": [path for path, _text in files],
        "file_summaries": file_summaries,
        "content_sha256": content_digest.hexdigest(),
        "sft_jsonl": by_path[f"{PACKAGE_ROOT}/data/charles_sft.jsonl"],
        "dpo_jsonl": by_path[f"{PACKAGE_ROOT}/data/charles_dpo.jsonl"],
        "train_config": by_path[f"{PACKAGE_ROOT}/configs/train_sft.yaml"],
        "readme": by_path[f"{PACKAGE_ROOT}/data/README.md"],
        "check_jsonl_script": by_path[f"{PACKAGE_ROOT}/scripts/check_jsonl.py"],
        "split_script": by_path[f"{PACKAGE_ROOT}/scripts/split_canary_val.py"],
        "validation": validation,
    }


def package_bytes(session: Session, *, include_split: bool = False, val_ratio: float = 0.05, seed: int = 42) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for path, text in package_file_contents(
            session,
            include_split=include_split,
            val_ratio=val_ratio,
            seed=seed,
        ):
            archive.writestr(path, text)
    return buffer.getvalue()


def write_package_zip(session: Session) -> Path:
    content = package_bytes(session)
    export_dir = Path(settings.storage_root) / "exports"
    export_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    path = export_dir / f"charles-model-{timestamp}.zip"
    path.write_bytes(content)
    return path


def touch_updated(model: Any) -> None:
    model.updated_at = utcnow()


def _message_content(messages: Any, role: str) -> str:
    if not isinstance(messages, list):
        return ""
    for message in messages:
        if isinstance(message, dict) and message.get("role") == role:
            return str(message.get("content") or "")
    return ""


def _starter_id(prefix: str, artifact_id: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9]+", "-", artifact_id).strip("-").lower()
    return f"{prefix}-{cleaned[:18] or 'unknown'}"


def import_approved_workbench_exports(session: Session) -> Dict[str, Any]:
    ensure_seed_data(session)
    created_sft_ids: List[str] = []
    created_dpo_ids: List[str] = []
    skipped_existing_ids: List[str] = []

    sft_rows = export_dry_run(session, "sft", include_candidates=False)["included"]
    for row in sft_rows:
        artifact_id = str(row.get("artifact_id") or "")
        example_id = _starter_id("wb-sft", artifact_id)
        existing = session.exec(select(ModelStarterSFTExample).where(ModelStarterSFTExample.example_id == example_id)).first()
        if existing and existing.status != "deleted":
            skipped_existing_ids.append(example_id)
            continue
        payload = row.get("payload") if isinstance(row.get("payload"), dict) else {}
        messages = payload.get("messages")
        metadata = payload.get("metadata") if isinstance(payload.get("metadata"), dict) else {}
        instruction = _message_content(messages, "user")
        response = _message_content(messages, "assistant")
        if not instruction.strip() or not response.strip():
            continue
        example = existing or ModelStarterSFTExample(example_id=example_id, instruction="", response="")
        example.example_id = example_id
        example.instruction = instruction
        example.response = response
        example.voice = str(metadata.get("voice_mode") or "father_to_adam")
        example.tone = str(metadata.get("artifact_mode") or "sft")
        example.provenance = f"Imported from approved Workbench SFT artifact {artifact_id}"
        example.consent_status = "approved_workbench_export"
        example.pii_tags = []
        example.notes = str(metadata.get("context") or "")
        example.status = "active"
        touch_updated(example)
        session.add(example)
        created_sft_ids.append(example_id)

    dpo_rows = export_dry_run(session, "dpo", include_candidates=False)["included"]
    for row in dpo_rows:
        artifact_id = str(row.get("artifact_id") or "")
        example_id = _starter_id("wb-dpo", artifact_id)
        existing = session.exec(select(ModelStarterDPOPair).where(ModelStarterDPOPair.example_id == example_id)).first()
        if existing and existing.status != "deleted":
            skipped_existing_ids.append(example_id)
            continue
        payload = row.get("payload") if isinstance(row.get("payload"), dict) else {}
        input_payload = payload.get("input") if isinstance(payload.get("input"), dict) else {}
        metadata = payload.get("metadata") if isinstance(payload.get("metadata"), dict) else {}
        prompt = _message_content(input_payload.get("messages"), "user")
        chosen = str(payload.get("preferred_output") or "")
        rejected = str(payload.get("non_preferred_output") or "")
        if not prompt.strip() or not chosen.strip() or not rejected.strip() or chosen.strip() == rejected.strip():
            continue
        pair = existing or ModelStarterDPOPair(example_id=example_id, prompt="", chosen="", rejected="")
        pair.example_id = example_id
        pair.prompt = prompt
        pair.chosen = chosen
        pair.rejected = rejected
        pair.provenance = f"Imported from approved Workbench DPO artifact {artifact_id}"
        reason = metadata.get("reason")
        pair.why_chosen = "; ".join(str(item) for item in reason) if isinstance(reason, list) else str(reason or "")
        pair.notes = str(metadata.get("context") or "")
        pair.status = "active"
        touch_updated(pair)
        session.add(pair)
        created_dpo_ids.append(example_id)

    session.commit()
    return {
        "imported_sft_count": len(created_sft_ids),
        "imported_dpo_count": len(created_dpo_ids),
        "skipped_existing_count": len(skipped_existing_ids),
        "created_sft_ids": created_sft_ids,
        "created_dpo_ids": created_dpo_ids,
        "skipped_existing_ids": skipped_existing_ids,
    }
